export type TranslationKey = keyof typeof TRANSLATIONS.ml;

export function t(lang: Language, key: TranslationKey): string {
  return TRANSLATIONS[lang][key];
}

export function getLocalizedName(
  item: { nameMl: string; nameEn: string } | undefined | null,
  lang: Language,
  fallback = '—',
): string {
  if (!item) return fallback;
  if (lang === 'ml') {
    return item.nameMl.trim() || item.nameEn.trim() || fallback;
  }
  return item.nameEn.trim() || item.nameMl.trim() || fallback;
}

export function formatCurrency(amount: number, showSign = false): string {
  const abs = Math.abs(amount);
  const formatted = new Intl.NumberFormat('en-IN', {
    minimumFractionDigits: Number.isInteger(abs) ? 0 : 2,
    maximumFractionDigits: 2,
  }).format(abs);

  if (amount < 0) return `-₹${formatted}`;
  if (showSign && amount > 0) return `+₹${formatted}`;
  return `₹${formatted}`;
}

export function formatDisplayDate(isoDate: string, lang: Language): string {
  if (!isoDate) return '';
  const parts = isoDate.split('-').map(Number);
  if (parts.length !== 3 || parts.some(Number.isNaN)) return isoDate;
  const [year, month, day] = parts;
  const dateObj = new Date(year, month - 1, day);
  return new Intl.DateTimeFormat(lang === 'ml' ? 'ml-IN' : 'en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
  }).format(dateObj);
}
